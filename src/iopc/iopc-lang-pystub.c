#define STUB_HEADER \
    "######################################################\n"               \
    "# THIS FILE IS AUTOGENERATED DO NOT MODIFY DIRECTLY! #\n"               \
    "######################################################\n"               \
    "# ruff: noqa: CPY001, E501, F401, I001, N801, N802, N815, RUF036, "     \
    "RUF100, UP013\n"                                                        \
    "\n"                                                                     \
