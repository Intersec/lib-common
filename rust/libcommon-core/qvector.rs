//! Module to interact with `qv_t` (qvector) in Rust.
//!
//! [`QVector`] wraps a C `qvector_t` and behaves like a [`Vec`]. It derefs to a slice, so the
//! whole slice API (indexing, iteration, sorting, searching) is available on it.
//!
//! One method differs from [`Vec`]: [`QVector::splice`] takes a slice and returns the inserted
//! elements, where [`Vec::splice`] takes an iterator and returns the removed ones.
//!
//! # Allocator
//!
//! The allocator is chosen by the constructor and cannot change afterwards:
//!
//! - [`QVector::new`] allocates with libc.
//! - [`QVector::t_new`] allocates on the `t_pool` of a [`TScope`]. The vector borrows the
//!   [`TScope`], so it cannot outlive it.
//! - [`QVector::from_stack_buffer`] starts on a caller-provided buffer, and falls back to libc if
//!   it has to grow.
//!
//! # Element ownership
//!
//! A [`QVector`] owns its elements: they are dropped when the vector is dropped. This is the
//! equivalent of the C `qv_deep_wipe()`. Use an owning element type to get it:
//!
//! - `QVector<lstr_t>` only frees its buffer, like the C `qv_wipe()`. Use it for vectors of
//!   borrowed values, which is what most C functions fill.
//! - `QVector<OwnedUtf8Lstr>` also calls `lstr_wipe()` on every element, like the C
//!   `qv_deep_wipe()`.
//!
//! Both have the same layout, so both can be passed to C.
//!
//! # Interfacing with C
//!
//! Every generated `qv_t` type implements [`QVectorType`]. No conversion ever copies the elements:
//! a `qv_t` and a [`QVector`] have the same layout, so only the descriptor moves.
//!
//! A C prototype takes a `qv_t` by pointer, so that is what the conversions take too. The element
//! type comes from the pointer, so it never has to be named:
//!
//! - [`QVector::from_c_ptr`] and [`QVector::from_c_ptr_mut`] borrow a vector that C owns, through
//!   a pointer. [`QVector::from_c_ptr_opt`] and [`QVector::from_c_ptr_mut_opt`] accept a null one.
//! - [`QVector::borrow_c`] and [`QVector::borrow_c_mut`] do the same from a reference.
//! - [`QVector::as_c_ptr`] and [`QVector::as_mut_c_ptr`] pass a vector to a C function.
//! - [`QVector::take_from_c_ptr`] and [`QVector::move_into_c_ptr`] transfer the ownership of the
//!   buffer through a pointer.
//! - [`QVector::from_c`] and [`QVector::into_c`] do the same by value, for a `qv_t` held by value.

use std::fmt;
use std::iter::FusedIterator;
use std::marker::PhantomData;
use std::mem::{ManuallyDrop, MaybeUninit};
use std::ops::{Bound, Deref, DerefMut, RangeBounds};
use std::os::raw::{c_int, c_void};
use std::ptr;
use std::ptr::NonNull;
use std::slice;

use crate::bindings::{
    __qvector_grow, mem_pool_static, mem_pool_t, qvector_growlen, qvector_optimize, qvector_reset,
    qvector_splice, qvector_t, qvector_wipe, t_pool,
};
use crate::helpers::{slice_from_nullable_raw_parts, slice_from_nullable_raw_parts_mut};
use crate::mem_stack::TScope;

// {{{ QVectorType

/// Trait implemented by every `qv_t` type generated by `bindgen`.
///
/// It binds a C vector type to its element type, so that a [`QVector`] can be converted to and
/// from the matching C type.
///
/// The implementations are generated by `waf-cargo-build`; do not write them by hand.
///
/// # Safety
///
/// The implementor must have the layout of a `qvector_t`, and [`Self::Element`] must be the exact
/// element type of the C vector.
pub unsafe trait QVectorType {
    /// The element type of the C vector.
    type Element;
}

// }}}
// {{{ QVector

/// Wrapper around a C `qv_t` for safe manipulation in Rust.
///
/// See the [module documentation](self) for the allocator and element ownership rules.
#[repr(transparent)]
pub struct QVector<'a, T> {
    qv: qvector_t,

    // `&'a ()` ties the vector to its allocator scope, `T` makes the vector own its elements.
    _marker: PhantomData<(&'a (), T)>,
}

// The C code accesses the vector through a `qvector_t` pointer.
const _: () = {
    assert!(size_of::<QVector<'static, u8>>() == size_of::<qvector_t>());
    assert!(align_of::<QVector<'static, u8>>() == align_of::<qvector_t>());
};

impl<'a, T> QVector<'a, T> {
    // {{{ Constructors

    /// Create an empty vector allocated by libc.
    pub const fn new() -> Self {
        Self::with_mp(ptr::null_mut())
    }

    /// Create a vector allocated by libc with room for `capacity` elements.
    pub fn with_capacity(capacity: usize) -> Self {
        let mut vec = Self::new();

        vec.reserve(capacity);
        vec
    }

    /// Create an empty vector allocated on the `t_pool` of `t_scope`.
    ///
    /// The vector borrows the [`TScope`], so it is dropped before the scope is popped.
    pub fn t_new(_t_scope: &'a TScope) -> Self {
        Self::with_mp(unsafe { t_pool() })
    }

    /// Create a vector allocated on the `t_pool` of `t_scope` with room for `capacity` elements.
    pub fn t_with_capacity(t_scope: &'a TScope, capacity: usize) -> Self {
        let mut vec = Self::t_new(t_scope);

        vec.reserve(capacity);
        vec
    }

    /// Create an empty vector using a caller-provided buffer.
    ///
    /// This is the equivalent of the C `qv_inita()`. The vector uses `mem_pool_static`, so it
    /// falls back to libc if it grows past the buffer.
    ///
    /// # Panics
    ///
    /// The buffer length does not fit in a C `int`.
    pub fn from_stack_buffer(buffer: &'a mut [MaybeUninit<T>]) -> Self {
        let size = c_int::try_from(buffer.len()).expect("buffer too large for a qvector");

        Self {
            qv: qvector_t {
                tab: buffer.as_mut_ptr().cast::<u8>(),
                mp: &raw mut mem_pool_static,
                len: 0,
                size,
            },
            _marker: PhantomData,
        }
    }

    /// Create an empty vector using the given memory pool.
    const fn with_mp(mp: *mut mem_pool_t) -> Self {
        Self {
            qv: qvector_t {
                tab: ptr::null_mut(),
                mp,
                len: 0,
                size: 0,
            },
            _marker: PhantomData,
        }
    }

    /// Collect an iterator into a vector allocated on the `t_pool` of `t_scope`.
    ///
    /// This is the `t_pool` counterpart of [`Iterator::collect`], which can only build a vector
    /// allocated by libc because it cannot receive a [`TScope`].
    pub fn t_from_iter<I>(t_scope: &'a TScope, iter: I) -> Self
    where
        I: IntoIterator<Item = T>,
    {
        let iter = iter.into_iter();
        let mut vec = Self::t_with_capacity(t_scope, iter.size_hint().0);

        vec.extend(iter);
        vec
    }

    // }}}
    // {{{ Accessors

    /// Get the number of elements of the vector.
    #[inline]
    pub const fn len(&self) -> usize {
        self.qv.len as usize
    }

    /// Check whether the vector is empty.
    #[inline]
    pub const fn is_empty(&self) -> bool {
        self.qv.len == 0
    }

    /// Get the number of elements the vector can hold without reallocating.
    #[inline]
    pub const fn capacity(&self) -> usize {
        self.qv.size as usize
    }

    /// Get the elements of the vector as a slice.
    #[inline]
    pub const fn as_slice(&self) -> &[T] {
        unsafe { slice_from_nullable_raw_parts(self.qv.tab.cast::<T>(), self.len()) }
    }

    /// Get the elements of the vector as a mutable slice.
    #[inline]
    pub const fn as_mut_slice(&mut self) -> &mut [T] {
        unsafe { slice_from_nullable_raw_parts_mut(self.qv.tab.cast::<T>(), self.len()) }
    }

    /// Get a raw pointer to the elements of the vector.
    ///
    /// The pointer is null if the vector never allocated.
    #[inline]
    pub const fn as_ptr(&self) -> *const T {
        self.qv.tab.cast::<T>()
    }

    /// Get a mutable raw pointer to the elements of the vector.
    ///
    /// The pointer is null if the vector never allocated.
    #[inline]
    pub const fn as_mut_ptr(&mut self) -> *mut T {
        self.qv.tab.cast::<T>()
    }

    // }}}
    // {{{ Capacity

    /// Reserve room for at least `additional` more elements.
    ///
    /// The capacity is never reduced.
    ///
    /// # Panics
    ///
    /// The resulting length does not fit in a C `int`.
    pub fn reserve(&mut self, additional: usize) {
        let len = self.len();

        if len + additional <= self.capacity() {
            return;
        }
        Self::assert_c_len(len + additional);

        unsafe {
            __qvector_grow(
                &raw mut self.qv,
                size_of::<T>(),
                align_of::<T>(),
                additional as c_int,
            );
        }
    }

    /// Release the memory that the vector does not use.
    pub fn shrink_to_fit(&mut self) {
        unsafe {
            qvector_optimize(&raw mut self.qv, size_of::<T>(), align_of::<T>(), 0, 0);
        }
    }

    // }}}
    // {{{ Mutators

    /// Append an element to the vector.
    ///
    /// # Panics
    ///
    /// The resulting length does not fit in a C `int`.
    pub fn push(&mut self, value: T) {
        assert!(self.qv.len < c_int::MAX, "qvector length overflow");

        let slot = unsafe { qvector_growlen(&raw mut self.qv, size_of::<T>(), align_of::<T>(), 1) };

        unsafe {
            slot.cast::<T>().write(value);
        }
    }

    /// Remove the last element of the vector and return it, or `None` if it is empty.
    pub fn pop(&mut self) -> Option<T> {
        let len = self.len();

        if len == 0 {
            return None;
        }
        self.qv.len -= 1;
        Some(unsafe { self.as_ptr().add(len - 1).read() })
    }

    /// Insert an element at `index`, shifting the following elements to the right.
    ///
    /// # Panics
    ///
    /// `index` is greater than the length, or the resulting length does not fit in a C `int`.
    pub fn insert(&mut self, index: usize, value: T) {
        assert!(index <= self.len(), "insertion index out of bounds");
        assert!(self.qv.len < c_int::MAX, "qvector length overflow");

        let slot = unsafe {
            qvector_splice(
                &raw mut self.qv,
                size_of::<T>(),
                align_of::<T>(),
                index as c_int,
                0,
                ptr::null(),
                1,
            )
        };

        unsafe {
            slot.cast::<T>().write(value);
        }
    }

    /// Remove the element at `index` and return it, shifting the following elements to the left.
    ///
    /// # Panics
    ///
    /// `index` is out of bounds.
    pub fn remove(&mut self, index: usize) -> T {
        assert!(index < self.len(), "removal index out of bounds");

        let value = unsafe { self.as_ptr().add(index).read() };

        unsafe {
            qvector_splice(
                &raw mut self.qv,
                size_of::<T>(),
                align_of::<T>(),
                index as c_int,
                1,
                ptr::null(),
                0,
            );
        }
        value
    }

    /// Remove the element at `index` and return it, replacing it with the last element.
    ///
    /// This does not preserve the order of the elements, but runs in constant time.
    ///
    /// # Panics
    ///
    /// `index` is out of bounds.
    pub fn swap_remove(&mut self, index: usize) -> T {
        let len = self.len();

        assert!(index < len, "swap_remove index out of bounds");

        unsafe {
            let tab = self.as_mut_ptr();
            let value = tab.add(index).read();

            if index + 1 != len {
                ptr::copy_nonoverlapping(tab.add(len - 1), tab.add(index), 1);
            }
            self.qv.len -= 1;
            value
        }
    }

    /// Drop the elements after the first `len` ones.
    ///
    /// This does nothing if `len` is greater than the length.
    pub fn truncate(&mut self, len: usize) {
        let old_len = self.len();

        if len >= old_len {
            return;
        }

        // Shorten the vector first, so that the elements are not dropped twice if dropping one of
        // them panics.
        self.qv.len = len as c_int;

        let tail =
            ptr::slice_from_raw_parts_mut(unsafe { self.as_mut_ptr().add(len) }, old_len - len);

        unsafe {
            ptr::drop_in_place(tail);
        }
    }

    /// Drop every element of the vector.
    ///
    /// The buffer is kept, unless it is large enough that the C code decides to release it.
    pub fn clear(&mut self) {
        self.truncate(0);
        unsafe {
            qvector_reset(&raw mut self.qv, size_of::<T>());
        }
    }

    /// Append a copy of every element of `other` to the vector.
    ///
    /// # Panics
    ///
    /// The resulting length does not fit in a C `int`.
    pub fn extend_from_slice(&mut self, other: &[T])
    where
        T: Copy,
    {
        if other.is_empty() {
            return;
        }

        Self::assert_c_len(self.len() + other.len());

        let extra = Self::to_c_int(other.len());
        let slot =
            unsafe { qvector_growlen(&raw mut self.qv, size_of::<T>(), align_of::<T>(), extra) };

        unsafe {
            ptr::copy_nonoverlapping(other.as_ptr(), slot.cast::<T>(), other.len());
        }
    }

    /// Replace the elements of `range` with a copy of `values`.
    ///
    /// This is the equivalent of the C `qv_splice()`. The removed elements are discarded, which is
    /// why the element type is `Copy`: it has nothing to release.
    ///
    /// Return the inserted elements. [`Vec::splice`] instead yields the removed ones: the C
    /// function overwrites them, so it cannot hand them back.
    ///
    /// # Panics
    ///
    /// `range` is out of bounds, or the resulting length does not fit in a C `int`.
    pub fn splice<R>(&mut self, range: R, values: &[T]) -> &mut [T]
    where
        R: RangeBounds<usize>,
        T: Copy,
    {
        let len = self.len();
        let (pos, rm_len) = Self::resolve_range(&range, len);

        Self::assert_c_len(len - rm_len + values.len());

        // `qvector_splice()` copies the values with `memcpy()`, so they must not overlap the
        // vector. The borrow checker guarantees it: `values` cannot borrow from `self`.
        //
        // An empty slice has a dangling pointer, so pass a null pointer instead: the C code then
        // skips the copy.
        let inserted_values = if values.is_empty() {
            ptr::null()
        } else {
            values.as_ptr().cast::<c_void>()
        };

        unsafe {
            qvector_splice(
                &raw mut self.qv,
                size_of::<T>(),
                align_of::<T>(),
                Self::to_c_int(pos),
                Self::to_c_int(rm_len),
                inserted_values,
                Self::to_c_int(values.len()),
            );
        }

        &mut self.as_mut_slice()[pos..pos + values.len()]
    }

    /// Remove the elements of `range` and return an iterator over them.
    ///
    /// The elements that the iterator does not yield are dropped when it is dropped, and the
    /// remaining elements of the vector are moved back to close the gap.
    ///
    /// # Panics
    ///
    /// `range` is out of bounds.
    pub fn drain<R>(&mut self, range: R) -> Drain<'_, 'a, T>
    where
        R: RangeBounds<usize>,
    {
        let len = self.len();
        let (pos, rm_len) = Self::resolve_range(&range, len);

        // Shorten the vector to the start of the range. The drained elements and the elements
        // after them are now only reachable through the `Drain`, so leaking it leaks them instead
        // of dropping them twice.
        self.qv.len = pos as c_int;

        Drain {
            vec: NonNull::from(self),
            start: pos,
            end: pos + rm_len,
            tail_start: pos + rm_len,
            tail_len: len - pos - rm_len,
            _marker: PhantomData,
        }
    }

    // }}}
    // {{{ C interoperability

    /// Get the vector as a pointer to the matching C `qv_t` type.
    #[inline]
    pub const fn as_c_ptr<Q>(&self) -> *const Q
    where
        Q: QVectorType<Element = T>,
        T: Copy,
    {
        (&raw const self.qv).cast::<Q>()
    }

    /// Get the vector as a mutable pointer to the matching C `qv_t` type.
    ///
    /// The element type is `Copy`, so the C code cannot make the vector own resources that it
    /// would then have to release. Use [`Self::as_mut_c_ptr_unchecked`] for an owning element
    /// type.
    #[inline]
    pub const fn as_mut_c_ptr<Q>(&mut self) -> *mut Q
    where
        Q: QVectorType<Element = T>,
        T: Copy,
    {
        (&raw mut self.qv).cast::<Q>()
    }

    /// Get the vector as a mutable pointer to the matching C `qv_t` type, for any element type.
    ///
    /// # Safety
    ///
    /// The vector owns its elements: it drops them when it is dropped. The C code must leave it
    /// with `len` elements that it is allowed to drop. In particular, a C function that fills the
    /// vector with borrowed values must not be called through this method.
    #[inline]
    pub const unsafe fn as_mut_c_ptr_unchecked<Q>(&mut self) -> *mut Q
    where
        Q: QVectorType<Element = T>,
    {
        (&raw mut self.qv).cast::<Q>()
    }

    /// Borrow a C vector as a [`QVector`].
    ///
    /// The C vector keeps its ownership: the returned reference never drops it.
    ///
    /// # Safety
    ///
    /// `qv` must be a valid C vector: its first `len` elements must be initialized.
    #[inline]
    pub const unsafe fn borrow_c<Q>(qv: &Q) -> &Self
    where
        Q: QVectorType<Element = T>,
    {
        unsafe { &*ptr::from_ref(qv).cast::<Self>() }
    }

    /// Borrow a C vector as a mutable [`QVector`].
    ///
    /// The C vector keeps its ownership: the returned reference never drops it.
    ///
    /// # Safety
    ///
    /// `qv` must be a valid C vector: its first `len` elements must be initialized.
    #[inline]
    pub const unsafe fn borrow_c_mut<Q>(qv: &mut Q) -> &mut Self
    where
        Q: QVectorType<Element = T>,
    {
        unsafe { &mut *ptr::from_mut(qv).cast::<Self>() }
    }

    /// Borrow a C vector through a pointer.
    ///
    /// The element type comes from the pointer, so it never has to be named:
    ///
    /// ```ignore
    /// let vec = unsafe { QVector::from_c_ptr(qv) };  // qv: *const qv_lstr_t
    /// ```
    ///
    /// The C vector keeps its ownership: the returned reference never drops it.
    ///
    /// # Panics
    ///
    /// `qv` is null. Use [`Self::from_c_ptr_opt`] for a pointer that can be null.
    ///
    /// # Safety
    ///
    /// `qv` must point to a valid C vector, whose first `len` elements are initialized, and which
    /// outlives the returned reference.
    #[inline]
    pub unsafe fn from_c_ptr<'x, Q>(qv: *const Q) -> &'x Self
    where
        Q: QVectorType<Element = T>,
    {
        assert!(!qv.is_null(), "QVector::from_c_ptr called with NULL");
        unsafe { &*qv.cast::<Self>() }
    }

    /// Borrow a C vector through a mutable pointer.
    ///
    /// The element type comes from the pointer, so it never has to be named:
    ///
    /// ```ignore
    /// let vec = unsafe { QVector::from_c_ptr_mut(qv) };  // qv: *mut qv_lstr_t
    /// ```
    ///
    /// The C vector keeps its ownership: the returned reference never drops it.
    ///
    /// # Panics
    ///
    /// `qv` is null. Use [`Self::from_c_ptr_mut_opt`] for a pointer that can be null.
    ///
    /// # Safety
    ///
    /// `qv` must point to a valid C vector, whose first `len` elements are initialized, and which
    /// outlives the returned reference. Nothing else may use the vector meanwhile.
    #[inline]
    pub unsafe fn from_c_ptr_mut<'x, Q>(qv: *mut Q) -> &'x mut Self
    where
        Q: QVectorType<Element = T>,
    {
        assert!(!qv.is_null(), "QVector::from_c_ptr_mut called with NULL");
        unsafe { &mut *qv.cast::<Self>() }
    }

    /// Borrow a C vector through a pointer that can be null.
    ///
    /// Return `None` if `qv` is null. Many C functions take a `nullable` vector to mean "do not
    /// report this".
    ///
    /// # Safety
    ///
    /// See [`Self::from_c_ptr`], for a pointer that is not null.
    #[inline]
    pub unsafe fn from_c_ptr_opt<'x, Q>(qv: *const Q) -> Option<&'x Self>
    where
        Q: QVectorType<Element = T>,
    {
        if qv.is_null() {
            return None;
        }
        Some(unsafe { &*qv.cast::<Self>() })
    }

    /// Borrow a C vector through a mutable pointer that can be null.
    ///
    /// Return `None` if `qv` is null.
    ///
    /// # Safety
    ///
    /// See [`Self::from_c_ptr_mut`], for a pointer that is not null.
    #[inline]
    pub unsafe fn from_c_ptr_mut_opt<'x, Q>(qv: *mut Q) -> Option<&'x mut Self>
    where
        Q: QVectorType<Element = T>,
    {
        if qv.is_null() {
            return None;
        }
        Some(unsafe { &mut *qv.cast::<Self>() })
    }

    /// Take the ownership of a C vector, through a pointer.
    ///
    /// The elements are not copied: only the descriptor is moved. `*qv` is left empty, with its
    /// memory pool untouched, so the C code can keep using it and its `qv_wipe()` has nothing left
    /// to release.
    ///
    /// This is the C idiom `*dst = *src; qv_init(src);`.
    ///
    /// # Panics
    ///
    /// `qv` is null.
    ///
    /// # Safety
    ///
    /// `qv` must point to a valid C vector that the caller owns, whose first `len` elements are
    /// initialized. Its memory pool must outlive `'a`.
    pub unsafe fn take_from_c_ptr<Q>(qv: *mut Q) -> Self
    where
        Q: QVectorType<Element = T>,
    {
        assert!(!qv.is_null(), "QVector::take_from_c_ptr called with NULL");

        let qv = qv.cast::<qvector_t>();
        let taken = unsafe { qv.read() };

        // Leave an empty vector behind, so that the C code cannot release the buffer a second
        // time. Keep its memory pool: a vector on the `t_pool` must stay on the `t_pool`.
        unsafe {
            qv.write(qvector_t {
                tab: ptr::null_mut(),
                mp: taken.mp,
                len: 0,
                size: 0,
            });
        }

        Self {
            qv: taken,
            _marker: PhantomData,
        }
    }

    /// Give the ownership of the vector to C, through a pointer.
    ///
    /// The elements are not copied: only the descriptor is moved. What `*qv` held is released
    /// first, so nothing leaks. The C code becomes responsible for the buffer.
    ///
    /// # Panics
    ///
    /// `qv` is null.
    ///
    /// # Safety
    ///
    /// `qv` must point to a valid C vector that the caller owns, and must not alias this vector:
    /// releasing what the target held would release the buffer being moved. Writing over an
    /// uninitialized vector is undefined behaviour; use [`Self::into_c`] to build a value from
    /// scratch.
    pub unsafe fn move_into_c_ptr<Q>(self, qv: *mut Q)
    where
        Q: QVectorType<Element = T>,
    {
        assert!(!qv.is_null(), "QVector::move_into_c_ptr called with NULL");

        // Release what the C vector held: its elements, then its buffer.
        unsafe {
            ptr::drop_in_place(qv.cast::<Self>());
        }

        // Do not run the destructor: the C vector now owns the buffer.
        let this = ManuallyDrop::new(self);

        unsafe {
            qv.cast::<Self>().write(ptr::from_ref(&*this).read());
        }
    }

    /// Take ownership of a C vector.
    ///
    /// The elements are not copied: only the descriptor is moved. The vector releases the buffer
    /// that the C code allocated when it is dropped.
    ///
    /// # Safety
    ///
    /// The caller must own `qv`, and the C code must not use it any more. Its first `len` elements
    /// must be initialized, and its memory pool must outlive `'a`.
    #[inline]
    pub unsafe fn from_c<Q>(qv: Q) -> Self
    where
        Q: QVectorType<Element = T>,
    {
        const { assert!(size_of::<Q>() == size_of::<Self>()) };
        const { assert!(align_of::<Q>() == align_of::<Self>()) };

        // Do not drop the C vector: this vector now owns the buffer.
        let qv = ManuallyDrop::new(qv);

        unsafe { ptr::from_ref(&*qv).cast::<Self>().read() }
    }

    /// Give ownership of the vector to C.
    ///
    /// The elements are not copied: only the descriptor is moved. The C code becomes responsible
    /// for releasing the buffer, with `qv_wipe()`.
    #[inline]
    pub fn into_c<Q>(self) -> Q
    where
        Q: QVectorType<Element = T>,
    {
        const { assert!(size_of::<Q>() == size_of::<Self>()) };
        const { assert!(align_of::<Q>() == align_of::<Self>()) };

        // Do not run the destructor: the C vector now owns the buffer.
        let this = ManuallyDrop::new(self);

        unsafe { ptr::from_ref(&*this).cast::<Q>().read() }
    }

    // }}}
    // {{{ Helpers

    /// Convert a length to a C `int`.
    ///
    /// # Panics
    ///
    /// The length does not fit in a C `int`.
    fn to_c_int(len: usize) -> c_int {
        c_int::try_from(len).expect("qvector length overflow")
    }

    /// Check that a length fits in a C `int`.
    ///
    /// # Panics
    ///
    /// The length does not fit in a C `int`.
    fn assert_c_len(len: usize) {
        assert!(c_int::try_from(len).is_ok(), "qvector length overflow");
    }

    /// Resolve a range into a start position and a number of elements.
    ///
    /// # Panics
    ///
    /// The range is out of bounds, or it starts after it ends.
    fn resolve_range<R>(range: &R, len: usize) -> (usize, usize)
    where
        R: RangeBounds<usize>,
    {
        let start = match range.start_bound() {
            Bound::Included(&start) => start,
            Bound::Excluded(&start) => start.checked_add(1).expect("invalid range start"),
            Bound::Unbounded => 0,
        };
        let end = match range.end_bound() {
            Bound::Included(&end) => end.checked_add(1).expect("invalid range end"),
            Bound::Excluded(&end) => end,
            Bound::Unbounded => len,
        };

        assert!(start <= end, "range starts after it ends");
        assert!(end <= len, "range out of bounds");
        (start, end - start)
    }

    // }}}
}

