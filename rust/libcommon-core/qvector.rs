// {{{ IntoIter

/// Owning iterator over the elements of a [`QVector`].
///
/// It is created by the [`IntoIterator`] implementation of [`QVector`].
pub struct IntoIter<'a, T> {
    vec: ManuallyDrop<QVector<'a, T>>,
    start: usize,
    end: usize,
}

impl<T> Iterator for IntoIter<'_, T> {
    type Item = T;

    fn next(&mut self) -> Option<T> {
        if self.start == self.end {
            return None;
        }

        let value = unsafe { self.vec.as_ptr().add(self.start).read() };

        self.start += 1;
        Some(value)
    }

    fn size_hint(&self) -> (usize, Option<usize>) {
        let remaining = self.end - self.start;

        (remaining, Some(remaining))
    }
}

impl<T> DoubleEndedIterator for IntoIter<'_, T> {
    fn next_back(&mut self) -> Option<T> {
        if self.start == self.end {
            return None;
        }
        self.end -= 1;
        Some(unsafe { self.vec.as_ptr().add(self.end).read() })
    }
}

impl<T> ExactSizeIterator for IntoIter<'_, T> {}

impl<T> FusedIterator for IntoIter<'_, T> {}

impl<T: fmt::Debug> fmt::Debug for IntoIter<'_, T> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_list().entries(self.as_slice()).finish()
    }
}

impl<T> IntoIter<'_, T> {
    /// Get the elements that the iterator did not yield yet.
    #[inline]
    pub fn as_slice(&self) -> &[T] {
        let tab = self.vec.as_ptr();

        if tab.is_null() {
            return &[];
        }

        unsafe { slice::from_raw_parts(tab.add(self.start), self.len_left()) }
    }

    /// Get the number of elements that the iterator did not yield yet.
    #[inline]
    const fn len_left(&self) -> usize {
        self.end - self.start
    }
}

impl<T> Drop for IntoIter<'_, T> {
    fn drop(&mut self) {
        // Drop the elements that were not yielded.
        let tab = self.vec.as_mut_ptr();

        if !tab.is_null() {
            let left =
                ptr::slice_from_raw_parts_mut(unsafe { tab.add(self.start) }, self.len_left());

            unsafe {
                ptr::drop_in_place(left);
            }
        }

        // Every element is dropped: let the vector release its buffer only.
        self.vec.qv.len = 0;
        unsafe {
            ManuallyDrop::drop(&mut self.vec);
        }
    }
}

