        vec.splice(1.., &[8]);
        assert_eq!(vec.as_slice(), &[9, 8]);

        vec.splice(0..=1, &[7, 7, 7]);
        assert_eq!(vec.as_slice(), &[7, 7, 7]);

        vec.splice(.., &[1, 2]);
        assert_eq!(vec.as_slice(), &[1, 2]);

        vec.splice(.., &[]);
