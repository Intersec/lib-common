impl<T> Drop for QVector<'_, T> {
    fn drop(&mut self) {
        // Drop the elements, then release the buffer. `qvector_wipe()` only releases the buffer
        // for the pools that are not frame-based, so this is correct for every allocator.
        let elements = ptr::slice_from_raw_parts_mut(self.as_mut_ptr(), self.len());

        unsafe {
            ptr::drop_in_place(elements);
            qvector_wipe(&raw mut self.qv, size_of::<T>());
        }
    }
}

impl<T> Default for QVector<'_, T> {
    fn default() -> Self {
        Self::new()
    }
}

